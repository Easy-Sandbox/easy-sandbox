def _is_relative_to(path: Path, parent: Path) -> bool:
    try:
        path.relative_to(parent)
    except ValueError:
        return False
    return True


def _rel(root: Path, path: Path) -> str:
    return path.relative_to(root).as_posix()


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _exclude(bucket: dict[str, list[str]], reason: str, rel: str) -> None:
    bucket.setdefault(reason, []).append(rel)


def _is_secret_name(name: str) -> bool:
    lower = name.lower()
    if lower == ".env":
        return True
    if lower.startswith(".env.") and not lower.endswith((".example", ".sample", ".template")):
        return True
    if lower.endswith((".pem", ".key", ".p12", ".pfx", ".tfvars")) or ".tfstate" in lower:
        return True
    if lower.startswith(("kubeconfig", "id_rsa", "id_ed25519", "credentials")):
        return True
    if lower in {".npmrc", ".pypirc", ".netrc", ".git-credentials"}:
        return True
    return lower == "secrets" or lower.startswith("secrets.")


def _looks_binary(path: Path) -> bool:
    try:
        chunk = path.read_bytes()[:8192]
    except OSError:
        return True
    return b"\x00" in chunk


def _looks_secret(path: Path) -> bool:
    try:
        text = path.read_bytes()[:_SCAN_BYTES].decode("utf-8", errors="ignore")
    except OSError:
        return True
    return any(pattern.search(text) for pattern in _SECRET_CONTENT)


def _ignore_files(project: Path) -> list[Path]:
    return [project / name for name in _IGNORE_NAMES if (project / name).is_file()]


def _reject_secret_context(
    project: Path,
    compiled: DockerIgnore,
    label: str,
    *,
    error: type[Exception] = AdoptRejectedError,
    suggestion: str | None = None,
) -> None:
    leaked: list[str] = []
    for current, dirnames, filenames in os.walk(project, followlinks=False):
        dirnames[:] = [d for d in dirnames if not (Path(current) / d).is_symlink()]
        for filename in filenames:
            if not _is_secret_name(filename):
                continue
            rel = _rel(project, Path(current) / filename)
            if not compiled.excludes(rel):
                leaked.append(rel)
    if not leaked:
        return
    sample = ", ".join(leaked[:8])
    message = (
        f"{label} does not exclude secret-named file(s): {sample}. "
        "Add ignore lines such as `**/.env`, `**/*.pem`, `**/id_rsa*`, "
        "`**/*.tfstate` (a bare `.env` only matches the directory root, and "
        "a later `!` line can re-include a file)."
    )
    if error is AdoptRejectedError:
        raise AdoptRejectedError(message, usage=False)
    raise AICodegenError(message, suggestion=suggestion)


def _reject_wheel_exclusion(
    compiled: DockerIgnore,
    label: str,
    *,
    error: type[Exception] = AdoptRejectedError,
    suggestion: str | None = None,
) -> None:
    if not compiled.excludes(_WHEEL_PROBE):
        return
    message = (
        f"{label} excludes *.whl, so 'ebx deploy' cannot inject the SDK wheel "
        "and the image would install easy-sandbox from PyPI instead. "
        "Remove the *.whl rule."
    )
    if error is AdoptRejectedError:
        raise AdoptRejectedError(message, usage=False)
    raise AICodegenError(message, suggestion=suggestion)


def _exposed_ports(dockerfile: str) -> set[int]:
    found: set[int] = set()
    for match in _EXPOSE_RE.finditer(dockerfile):
        for token in match.group(1).split():
            number = token.split("/", 1)[0]
            if number.isdigit():
                found.add(int(number))
    return found


def _check_ports(
    dockerfile: str,
    commands: str,
    data: Mapping[str, object],
    warnings: list[str],
) -> None:
    raw = data.get("ports") or []
    ports = {int(port) for port in raw} if isinstance(raw, list) else set()
    exposed = _exposed_ports(dockerfile)
    if SERVER_PORT not in ports or SERVER_PORT not in exposed:
        raise AICodegenError(
            f"template.yaml ports and Dockerfile EXPOSE must both include {SERVER_PORT} "
            "(the SandboxServer port).",
            suggestion="Regenerate, or add the port to both files.",
        )
    for port in sorted(ports - {SERVER_PORT}):
        if port not in exposed:
            warnings.append(f"Port {port} is in template.yaml but not EXPOSE.")
    if ports - {SERVER_PORT} and "subprocess" not in commands:
        warnings.append(
            "template.yaml declares a port besides "
            f"{SERVER_PORT}, but commands.py never starts a subprocess. "
            "The project's own service is expected to be launched from commands.py."
        )


def _plan_ignores(project: Path, generated: str | None) -> list[tuple[DockerIgnore, str]]:
    found = [(DockerIgnore.from_file(path), path.name) for path in _ignore_files(project)]
    if generated is not None:
        found.append((DockerIgnore.from_text(generated), ".dockerignore (generated)"))
    return found


def _check_copy_sources(
    project: Path,
    dockerfile: str,
    files: Mapping[str, str],
    ignores: list[tuple[DockerIgnore, str]],
    hint: str,
    warnings: list[str],
) -> None:
    for source in parse_copy_sources(dockerfile):
        if source.kind == "variable":
            warnings.append(
                f"Dockerfile line {source.line} copies {source.source!r}; "
                "build args are not checked."
            )
            continue
        if source.kind == "glob":
            if not source.source.endswith("*.whl"):
                warnings.append(
                    f"Dockerfile line {source.line} copies glob {source.source!r}, "
                    "which was not expanded."
                )
            continue
        rel = _normalise_source(source.source)
        if rel is None:
            raise AICodegenError(
                f"Dockerfile line {source.line} copies {source.source!r}, which escapes "
                "the project.",
                suggestion=hint,
            )
        if rel in files:
            if any(compiled.excludes(rel) for compiled, _label in ignores):
                raise AICodegenError(
                    f"Dockerfile copies {rel}, but an ignore file excludes it, so the "
                    "build context would not contain it.",
                    suggestion=hint,
                )
            continue
        candidate = project / rel
        if candidate.is_symlink() or not (candidate.is_file() or candidate.is_dir()):
            raise AICodegenError(
                f"Dockerfile line {source.line} copies {rel!r}, which is not in the project.",
                suggestion=hint,
            )
        if any(compiled.excludes(rel) for compiled, _label in ignores):
            raise AICodegenError(
                f"Dockerfile copies {rel}, but an ignore file excludes it.",
                suggestion=hint,
            )


def _normalise_source(source: str) -> str | None:
    text = source.replace("\\", "/").strip()
    while text.startswith("./"):
        text = text[2:]
    text = text.rstrip("/")
    if not text or text.startswith("/") or ".." in Path(text).parts:
        return None
    return text


def _snapshot(root: Path) -> dict[str, str]:
    found: dict[str, str] = {}
    for current, dirnames, filenames in os.walk(root, followlinks=False):
        dirnames[:] = [d for d in dirnames if not d.startswith(".")]
        for name in filenames:
            path = Path(current) / name
            if path.is_symlink():
                continue
            rel = path.relative_to(root).as_posix()
            try:
                found[rel] = hashlib.sha256(path.read_bytes()).hexdigest()
            except OSError:
                continue
    return found


def _not_applied(staged: StagedProject, *, taken: set[str]) -> tuple[str, ...]:
    after = _snapshot(staged.staging_dir)
    changed: list[str] = []
    for rel, digest in after.items():
        if rel in taken:
            continue
        if staged.manifest.get(rel) != digest:
            changed.append(rel)
    for rel in staged.manifest:
        if rel not in after and rel not in taken:
            changed.append(f"{rel} (deleted)")
    return tuple(sorted(changed))


def _assert_reserved(rel: str) -> None:
    if rel not in RESERVED_FILES or Path(rel).name != rel:
        raise AICodegenError(f"Refusing to write {rel!r}: not a reserved template file.")


def _assert_unlinked(project: Path, rel: str) -> None:
    current = project
    for part in Path(rel).parts:
        current = current / part
        if current.is_symlink():
            raise AdoptRejectedError(
                f"{rel} is a symlink (or sits under one); refusing to write through it.",
                usage=False,
            )


def _backup_path(target: Path) -> Path:
    candidate = target.with_name(target.name + ".ebx-bak")
    number = 1
    while candidate.exists() or candidate.is_symlink():
        candidate = target.with_name(f"{target.name}.ebx-bak.{number}")
        number += 1
    return candidate
