"""Adapt an existing project into a deployable template (``init --adopt``).

The coding agent never runs inside the user's project.  Candidate files are
copied into a staging directory, the agent writes there, and only the
reviewed whitelist (``Dockerfile``, ``commands.py``, ``template.yaml``, and a
generated ``.dockerignore``) is written back — after deterministic checks.
"""

