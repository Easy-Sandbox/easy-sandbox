# ---------------------------------------------------------------------------
# Case → file mapping
# ---------------------------------------------------------------------------

_CASE_FILES: dict[str, dict[str, str]] = {
    "python": {
        "template.yaml": _PYTHON_TEMPLATE_YAML,
        "Dockerfile": _PYTHON_DOCKERFILE,
        "commands.py": _PYTHON_COMMANDS,
        "README.md": _PYTHON_README,
    },
    "node": {
        "template.yaml": _NODE_TEMPLATE_YAML,
        "Dockerfile": _NODE_DOCKERFILE,
        "commands.py": _NODE_COMMANDS,
        "README.md": _NODE_README,
    },
    "minimal": {
        "template.yaml": _MINIMAL_TEMPLATE_YAML,
        "Dockerfile": _MINIMAL_DOCKERFILE,
        "README.md": _MINIMAL_README,
    },
}


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------


def available_cases() -> list[tuple[str, str]]:
    """Return a list of ``(case_name, short_description)`` for built-in scaffolds."""
    return list(_CASES)


def render_scaffold(case: str, name: str) -> dict[str, str]:
    """Render a scaffold case, substituting *name* into templates.

    Args:
        case: One of the built-in case names (``python``, ``node``, ``minimal``).
        name: Template name to substitute into ``template.yaml`` and other files.

    Returns:
        A dict mapping relative file names to their rendered content.

    Raises:
        ValueError: If *case* is not a recognised scaffold name.
    """
    templates = _CASE_FILES.get(case)
    if templates is None:
        valid = ", ".join(c[0] for c in _CASES)
        raise ValueError(f"Unknown scaffold case '{case}'. Valid cases: {valid}")
    # Sanitize name to prevent ValueError from stray braces
    safe_name = str(name).replace("{", "").replace("}", "")
    return {filename: content.format(name=safe_name) for filename, content in templates.items()}
