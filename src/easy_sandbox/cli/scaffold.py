"""Built-in template scaffolds for ``ebx template init``.

Provides pre-defined template cases (python, node, minimal) that generate
a complete set of files for a new sandbox template project.  Template strings
are embedded directly — examples/ is NOT read at runtime because it is not
packaged in the wheel.
"""

from __future__ import annotations

__all__ = [
    "available_cases",
    "render_scaffold",
]

# ---------------------------------------------------------------------------
# Case definitions: (name, description)
# ---------------------------------------------------------------------------

_CASES: list[tuple[str, str]] = [
    ("python", "Python 3.11 sandbox with shell, files, and code capabilities"),
    ("node", "Node.js 20 sandbox with shell, files, and code capabilities"),
    ("minimal", "Minimal template with template.yaml, Dockerfile, and README"),
]

# ---------------------------------------------------------------------------
# Template strings
# ---------------------------------------------------------------------------

_PYTHON_TEMPLATE_YAML = """\
name: {name}
version: "1.0.0"
description: "Python sandbox template"

base: python:3.11-slim

capabilities:
  - shell
  - files
  - code

resources:
  cpu: 2
  memory: 2048
"""

_PYTHON_DOCKERFILE = """\
FROM python:3.11-slim

ENV DEBIAN_FRONTEND=noninteractive

# Install easy-sandbox SDK.
# When building locally via `ebx template deploy`, the SDK wheel
# is automatically injected into the build context as .whl file.
COPY *.whl /tmp/
RUN if ls /tmp/*.whl 1>/dev/null 2>&1; then \\
        pip install --no-cache-dir /tmp/*.whl && rm -f /tmp/*.whl; \\
    else \\
        pip install --no-cache-dir easy-sandbox; \\
    fi

WORKDIR /app
COPY commands.py .

EXPOSE 9000
CMD ["python3", "commands.py"]
"""

_PYTHON_COMMANDS = """\
\"\"\"Custom commands for {name}.\"\"\"
from __future__ import annotations

from easy_sandbox.server import (
    CapabilityGroup,
    CommandRegistry,
    SandboxServer,
    default_table,
)

table = default_table()
table.enable_group(CapabilityGroup.FILE_OPS)
table.enable_group(CapabilityGroup.PROCESS)
table.enable_group(CapabilityGroup.SYSTEM)

registry = CommandRegistry()


@registry.command("hello", description="Say hello.")
def hello(name: str = "World") -> str:
    return f"Hello, {{name}}!"


registry.freeze()
server = SandboxServer(registry=registry)
server.serve(port=9000)
"""

_PYTHON_README = """\
# {name}

A Python sandbox template generated by `ebx template init`.

## Quick Start

```bash
# Build and deploy to the cloud
ebx template deploy . --acr-namespace <your-namespace>

# Or install into local cache first
ebx install .
```
"""

